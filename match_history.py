"""Cross-hand memory of how each seat has been playing, for the prompt.

Without this a model cannot form a read on its rival at all: `reset_hand`
clears the public chat and the seña bus at every hand boundary, so each
decision was previously made against a table with no past.

Everything recorded here is information a seat at the table would legitimately
hold:

  * ACTIONS are public -- everyone hears an envite, a paso, a no-quiero.
  * CARDS are recorded only for lances that actually reached a showdown, i.e.
    lances carrying an accepted (locked) envite, which is exactly when mus
    players turn their cards over.  A rival who folds everything reveals
    nothing, and that is a real property of the game, not a gap in the log.

The read that matters is per-seat and conditional: when THIS rival pushed on
THIS lance and was made to show, did they actually have it?  A team-level
"shown down N times" is the same number for both opponents and tells you
nothing about either.

Hidden state -- the current hand's cards, and hands that were never shown --
never enters the dossier.  The summary is generated by the harness from the
same ground truth for every model, so this measures whether a model USES a
read, not whether it can remember a transcript.
"""
from __future__ import annotations

from collections import defaultdict

from mus_engine import TEAM_OF

AGGRESSIVE = ("envido", "y-yo", "reenvido", "ordago")
SHOWDOWN_KEEP = 2          # most recent showdowns quoted verbatim


def _blank() -> dict:
    return {"decisions": 0, "bets": 0, "folds": 0, "faced_bets": 0,
            "calls": 0, "mus_asked": 0, "bets_shown": 0, "bets_caught": 0}


class MatchHistory:
    """Per-seat behavioural record for one match."""

    def __init__(self):
        self.seats: dict[int, dict] = defaultdict(_blank)
        self.showdowns: list[dict] = []
        self.hands = 0
        self._bet_this_hand: set[tuple[int, str]] = set()

    # ------------------------------------------------------------- record --
    def record_decision(self, seat: int, action: str | None, *,
                        lance: str | None = None,
                        facing_bet: bool = False,
                        holder_team: int | None = None) -> None:
        """Public actions only -- no cards, no strength, no truth."""
        if not action:
            return
        s = self.seats[seat]
        s["decisions"] += 1
        if action in AGGRESSIVE:
            s["bets"] += 1
            if lance:
                self._bet_this_hand.add((seat, lance))
        if action == "mus":
            s["mus_asked"] += 1
        # only a bet from the OTHER team is one this seat had to answer
        if facing_bet and holder_team is not None and holder_team != TEAM_OF[seat]:
            s["faced_bets"] += 1
            if action == "no-quiero":
                s["folds"] += 1
            elif action == "quiero":
                s["calls"] += 1

    def close_hand(self, engine, hand: int) -> None:
        """Record the lances that were actually shown down."""
        self.hands = hand
        shown = {name for name, _stake, _holder in engine.locked_envites}
        if shown:
            cards = {s: [str(c) for c in engine.hands.get(s, [])]
                     for s in range(4)}
            for j in engine.jugadas:
                if j.name not in shown:
                    continue
                self.showdowns.append({"hand": hand, "lance": j.name,
                                       "winner": j.winner_team, "cards": cards})
                # credit only the seats that actually pushed on this lance
                for seat in range(4):
                    if (seat, j.name) not in self._bet_this_hand:
                        continue
                    st = self.seats[seat]
                    st["bets_shown"] += 1
                    if j.winner_team is not None and j.winner_team != TEAM_OF[seat]:
                        st["bets_caught"] += 1
        self._bet_this_hand.clear()

    # ------------------------------------------------------------ render ---
    def _line(self, seat: int) -> str:
        s = self.seats[seat]
        bits = [f"bet {s['bets']}x in {s['decisions']} decisions"]
        if s["faced_bets"]:
            bits.append(f"folded to {s['folds']}/{s['faced_bets']} bets faced")
        if s["bets_shown"]:
            bits.append(f"of its bets that reached a showdown, "
                        f"{s['bets_caught']}/{s['bets_shown']} were with the "
                        f"weaker hand")
        else:
            bits.append("no bet of its own has been shown down yet")
        return "; ".join(bits) + "."

    def dossier(self, seat: int, max_showdowns: int = SHOWDOWN_KEEP) -> list[str]:
        if self.hands == 0:
            return []
        team = TEAM_OF[seat]
        rivals = [s for s in range(4) if TEAM_OF[s] != team]
        partner = [s for s in range(4) if TEAM_OF[s] == team and s != seat]
        out = [f"RIVAL HISTORY ({self.hands} hand(s) so far this match -- public "
               f"actions, plus cards from lances that reached a showdown):"]
        out.extend(f"  seat {s} (rival): {self._line(s)}" for s in rivals)
        out.extend(f"  seat {p} (your partner): {self._line(p)}"
                   for p in partner)
        recent = self.showdowns[-max_showdowns:]
        if recent:
            out.append("  Recent showdowns (cards were turned over):")
            for sd in recent:
                who = ("nobody" if sd["winner"] is None
                       else f"team {sd['winner']}")
                shown = "; ".join(
                    f"seat {s} held {', '.join(sd['cards'][s])}" for s in rivals)
                out.append(f"    hand {sd['hand']} {sd['lance']}, won by {who}:"
                           f" {shown}")
        return out
